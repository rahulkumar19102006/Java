// 4. Write a Java program to divide two numbers and display the result on screen.
public class Q4_DivideTwoNumbers {
    public static void main(String[] args) {
        double a = 22.5;
        double b = 4.5;
        double result = a / b;
        System.out.println("First number: " + a);
        System.out.println("Second number: " + b);
        System.out.println("Division (a / b): " + result);
    }
}
